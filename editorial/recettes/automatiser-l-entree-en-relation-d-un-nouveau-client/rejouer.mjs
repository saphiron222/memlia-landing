import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const dir = dirname(fileURLToPath(import.meta.url));
export function proposer(entree) {
  const sortie = (statut) => ({ dossier: entree.dossier, version: entree.version, statut, envois: 0, decisionVigilance: null });
  if (!entree.checklist) return sortie('REFUS : CHECKLIST ABSENTE');
  if (entree.reexamen) return sortie('REFUS : RÉEXAMEN CABINET');
  if (entree.pieces.some(p => p.dossier !== entree.dossier)) return sortie('REFUS : RÉFÉRENCE DIVERGENTE');
  if (entree.pieces.some(p => p.etat === 'illisible')) return sortie('REFUS : PIÈCE ILLISIBLE');
  const manque = entree.pieces.filter(p => p.etat === 'attendue').map(p => p.nom);
  if (manque.length) return sortie(`DEMANDE À VALIDER : ${manque.join(', ')}`);
  if (entree.pieces.some(p => p.etat !== 'qualifiee')) return sortie('EXAMEN DES PIÈCES À FAIRE');
  const decision = entree.decisionCabinet;
  if (!decision) return sortie('DÉCISION CABINET ATTENDUE');
  if (typeof decision !== 'object' || !['dossier', 'version', 'auteur', 'reference', 'resultat'].every(k => typeof decision[k] === 'string' && decision[k].trim())) return sortie('REFUS : DÉCISION INCOMPLÈTE');
  if (decision.dossier !== entree.dossier) return sortie('REFUS : DÉCISION AUTRE DOSSIER');
  if (decision.version !== entree.version) return sortie('REFUS : DÉCISION ANCIENNE VERSION');
  if (decision.resultat !== 'favorable') return sortie('REFUS : DÉCISION NON FAVORABLE');
  if (entree.signature !== entree.version) return sortie('REFUS : VERSION SIGNÉE DIFFÉRENTE');
  if (!entree.autorisation || entree.autorisation.dossier !== entree.dossier || entree.autorisation.version !== entree.version) return sortie('PASSATION À VALIDER');
  return sortie('PRÉPARER LA PASSATION');
}
const base = id => ({ dossier: id, version: 'V2', checklist: 'ENTREE-SOCIETE-1', reexamen: false, pieces: [ { dossier: id, nom: 'identification', etat: 'qualifiee' }, { dossier: id, nom: 'beneficiaire', etat: 'qualifiee' } ], decisionCabinet: { dossier: id, version: 'V2', auteur: 'ROLE-RESPONSABLE', reference: 'DEC-FICTIVE', resultat: 'favorable' }, signature: 'V2', autorisation: null, commentaireHumain: 'Demander un échange avant la passation.' });
const cas = Array.from({ length: 15 }, (_, i) => base(`D-${101 + i}`));
cas[1].pieces[0].etat = 'attendue';
cas[2].pieces[0].etat = 'illisible';
cas[3].pieces[1].etat = 'recue';
cas[4].decisionCabinet = null;
cas[5].signature = 'V1';
cas[6].autorisation = { dossier: 'D-107', version: 'V2', auteur: 'ROLE-RESPONSABLE' };
cas[7].checklist = null;
cas[8].pieces[0].dossier = 'D-999';
cas[9].reexamen = true;
for (const entree of cas.slice(10)) entree.autorisation = { dossier: entree.dossier, version: 'V2', auteur: 'ROLE-RESPONSABLE' };
cas[10].decisionCabinet.dossier = 'D-999';
cas[11].decisionCabinet.version = 'V1';
cas[12].decisionCabinet.resultat = 'defavorable';
cas[13].decisionCabinet.auteur = '';
delete cas[14].decisionCabinet.resultat;
const attendus = ['PASSATION À VALIDER', 'DEMANDE À VALIDER : identification', 'REFUS : PIÈCE ILLISIBLE', 'EXAMEN DES PIÈCES À FAIRE', 'DÉCISION CABINET ATTENDUE', 'REFUS : VERSION SIGNÉE DIFFÉRENTE', 'PRÉPARER LA PASSATION', 'REFUS : CHECKLIST ABSENTE', 'REFUS : RÉFÉRENCE DIVERGENTE', 'REFUS : RÉEXAMEN CABINET', 'REFUS : DÉCISION AUTRE DOSSIER', 'REFUS : DÉCISION ANCIENNE VERSION', 'REFUS : DÉCISION NON FAVORABLE', 'REFUS : DÉCISION INCOMPLÈTE', 'REFUS : DÉCISION INCOMPLÈTE'];
const rows = cas.map((entree, i) => {
  const avant = JSON.stringify(entree);
  const obtenu = proposer(entree);
  assert.equal(obtenu.statut, attendus[i]);
  assert.deepEqual(obtenu, proposer(entree));
  assert.equal(JSON.stringify(entree), avant);
  assert.equal(obtenu.envois, 0);
  assert.equal(obtenu.decisionVigilance, null);
  return { entree, attendu: attendus[i], obtenu };
});
const autorisationAncienne = { ...cas[6], version: 'V3', signature: 'V3', decisionCabinet: { ...cas[6].decisionCabinet, version: 'V3' } };
assert.equal(proposer(autorisationAncienne).statut, 'PASSATION À VALIDER');
const corps = readFileSync(join(dir, 'corps.md'), 'utf8');
for (const r of rows) assert.ok(corps.includes(r.entree.dossier) && corps.includes(r.obtenu.statut), `Sortie absente du corps : ${r.entree.dossier}`);
writeFileSync(join(dir, 'preuves/rejeu.json'), JSON.stringify({ fictif: true, executedAt: new Date().toISOString(), portee: 'Transitions administratives uniquement, aucune identification ou décision LCB-FT effectuée', cas: rows, assertions: { cas: rows.length, determinisme: true, saisiesProtegees: true, aucunEnvoi: true, aucuneDecisionVigilance: true, autorisationLieeVersion: true, concordanceCorps: true } }, null, 2) + '\n');
console.log('15 cas exécutés ; décision favorable liée au dossier/version exigée ; saisies protégées ; aucun envoi ni décision de vigilance ; autorisation périmée refusée ; corps concordant.');
