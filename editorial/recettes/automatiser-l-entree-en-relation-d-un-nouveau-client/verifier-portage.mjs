import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { reviewSha256, recipeSubstanceSha256 } from '../../../scripts/lib/blog-review-binding.mjs';
const dir = dirname(fileURLToPath(import.meta.url));
const read = name => readFileSync(join(dir, name));
const json = name => JSON.parse(read(name));
const acquired = json('revues-acquises.json');
const original = json('recette-acquise.json');
const current = json('recette.json');
assert.equal(original.cluster, 'organisation-cabinet');
assert.equal(original.cannibalization.risk, 'modere');
const transported = structuredClone(original);
transported.cluster = 'administratif-secretariat';
transported.cannibalization.risk = 'moyen';
assert.deepEqual({ ...current, date: transported.date, image: transported.image }, transported, 'Hors date et couverture revue v2, seuls deux libellés de registre sont traduits');
const qa = json('revue-image-v2.json');
assert.equal(qa.verdict, 'PASS');
assert.equal(current.image.source.generationId, qa.generationId);
assert.equal(current.image.alt, qa.alt);
assert.equal(reviewSha256(read('image-source.png')), qa.sourceSha256);
assert.equal(reviewSha256(read('corps.md').toString().trim()), acquired.subject.bodySha256);
const review = json('revues.json');
for (const field of ['editorial', 'business', 'sources', 'qualite', 'figures']) assert.deepEqual(review[field], acquired[field]);
assert.deepEqual(review.image.criteria, qa.criteria);
assert.equal(review.verdict, acquired.verdict);
